_MANUAL = {"none": "0", "zero": "0", "one": "1", "two": "2", "three": "3", "four": "4", "five": "5",
           "six": "6", "seven": "7", "eight": "8", "nine": "9", "ten": "10"}
_ARTICLES = {"a", "an", "the"}
_PERIOD_STRIP = re.compile(r"(?!<=\d)(\.)(?!\d)")
_COMMA_STRIP = re.compile(r"(\d)(,)(\d)")
_PUNCT = [";", r"/", "[", "]", '"', "{", "}", "(", ")", "=", "+", "\\", "_", "-", ">", "<", "@", "`", ",", "?", "!"]


def _punctuation(text: str) -> str:
    out = text
    for p in _PUNCT:
        if (p + " " in text or " " + p in text) or (re.search(_COMMA_STRIP, text) is not None):
            out = out.replace(p, "")
        else:
            out = out.replace(p, " ")
    return _PERIOD_STRIP.sub("", out)


def _digit_article(text: str) -> str:
    words = []
    for w in text.lower().split():
        w = _MANUAL.get(w, w)
        if w not in _ARTICLES:
            words.append(w)
    return " ".join(_CONTRACTIONS.get(w, w) for w in words)


def normalize(answer: str) -> str:
    answer = answer.replace("\n", " ").replace("\t", " ").strip()
    return _digit_article(_punctuation(answer))


def accuracy(prediction: str, gold_answers: list[str]) -> float:
    pred = normalize(prediction if isinstance(prediction, str) else "")
    gts = [normalize(a) for a in gold_answers]
    scores = []
    for i in range(len(gts)):
        others = gts[:i] + gts[i + 1 :]
        scores.append(min(1.0, sum(g == pred for g in others) / 3.0))
    return sum(scores) / max(1, len(scores))
